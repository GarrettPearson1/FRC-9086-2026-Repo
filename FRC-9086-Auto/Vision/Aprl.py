from dataclasses import dataclass

import cv2
import numpy as np
from pupil_apriltags import Detector, Detection

from Camera import Camera, Frame

import warnings

from CameraCalibrationData import CameraCalibrationData

@dataclass
class AprlTag:
    id: int
    camera_translation: np.ndarray # meters
    camera_rotation: np.ndarray # radians

    raw: Detection

"""
April tag detector
"""
class Aprl:
    def __init__(self,
                 family: str = "tag36h11",
                 nthreads: int = 1,
                 quad_decimate: float = 2.0,
                 quad_sigma: float = 0.0,
                 refine_edges: int = 1,
                 decode_sharpening: float = .25,
                 debug: bool = False):
        self.detector = Detector(
            families = family,
            nthreads = nthreads,
            quad_decimate = quad_decimate,
            quad_sigma = quad_sigma,
            refine_edges = refine_edges,
            decode_sharpening = decode_sharpening,
            debug = int(debug)
        )

    def detect(self, camera: Camera, square_size: float = .16) -> list[AprlTag]:
        frame = cv2.cvtColor(camera.frame, cv2.COLOR_BGR2GRAY)

        raw_detections: list[Detection] = self.detector.detect(frame)

        aprltags: list[AprlTag] = []

        for detection in raw_detections:
            rvec, tvec = Aprl.calculate_pose(camera.calibration, detection.corners, square_size)

            aprltags.append(AprlTag(
                detection.tag_id,
                tvec,
                rvec,

                detection
            ))

        return aprltags

    @staticmethod
    def rotation_matrix_to_euler_angles(R):
        sy = np.sqrt(R[0, 0] ** 2 + R[1, 0] ** 2)

        singular = sy < 1e-6

        if not singular:
            x = np.arctan2(R[2, 1], R[2, 2])
            y = np.arctan2(-R[2, 0], sy)
            z = np.arctan2(R[1, 0], R[0, 0])
        else:
            x = np.arctan2(-R[1, 2], R[1, 1])
            y = np.arctan2(-R[2, 0], sy)
            z = 0

        return np.degrees([x, y, z])


    # square_size = meters
    # This is slightly more accurate than letting pupil-tags handle pose estimation
    @staticmethod
    def calculate_pose(camera: CameraCalibrationData, image_points, square_size: float):
        object_points = np.array([
            [0.0, 0.0, 0.0],
            [square_size, 0.0, 0.0],
            [square_size, square_size, 0.0],
            [0.0, square_size, 0.0]
        ], dtype=np.float32)

        success, rvec, tvec = cv2.solvePnP(
            object_points,
            image_points,
            camera.matrix,
            camera.distCoeffs,
            flags=cv2.SOLVEPNP_ITERATIVE
        )

        if not success:
            raise RuntimeError("Pose estimation failed")

        return rvec, tvec

    @staticmethod
    def visualize(frame: Frame, tags: list[AprlTag]) -> Frame:
        for detection in tags:
            corners = detection.raw.corners
            corners = corners.astype(int)

            # Draw lines between the corners
            cv2.line(frame, tuple(corners[0]), tuple(corners[1]), (0, 255, 0), 2)
            cv2.line(frame, tuple(corners[1]), tuple(corners[2]), (0, 255, 0), 2)
            cv2.line(frame, tuple(corners[2]), tuple(corners[3]), (0, 255, 0), 2)
            cv2.line(frame, tuple(corners[3]), tuple(corners[0]), (0, 255, 0), 2)

            cv2.circle(frame, tuple(corners[0]), 5, (0, 0, 255), -1)
            cv2.circle(frame, tuple(corners[1]), 5, (0, 255, 0), -1)
            cv2.circle(frame, tuple(corners[2]), 5, (255, 0, 0), -1)
            cv2.circle(frame, tuple(corners[3]), 5, (0, 255, 255), -1)

            # Draw the center point
            center = detection.raw.center.astype(int)
            cv2.circle(frame, tuple(center), 5, (0, 0, 255), -1)

            # Add the tag ID text
            tag_id = detection.id
            cv2.putText(frame, f"ID: {tag_id}", tuple(center + np.array([10, 0])), cv2.FONT_HERSHEY_SIMPLEX, 0.5,
                        (255, 0, 0), 2)

            # Draw pose data if available
            pose_t = detection.camera_translation.flatten()  # Flatten the pose_t matrix to a vector
            pose_text_x = f"x: {pose_t[0]:.2f}m"
            pose_text_y = f"y: {pose_t[1]:.2f}m"
            pose_text_z = f"z: {pose_t[2]:.2f}m"
            cv2.putText(frame, pose_text_x, tuple(center + np.array([10, 20])), cv2.FONT_HERSHEY_SIMPLEX, 0.5,
                        (255, 0, 0), 2)
            cv2.putText(frame, pose_text_y, tuple(center + np.array([10, 40])), cv2.FONT_HERSHEY_SIMPLEX, 0.5,
                        (255, 0, 0), 2)
            cv2.putText(frame, pose_text_z, tuple(center + np.array([10, 60])), cv2.FONT_HERSHEY_SIMPLEX, 0.5,
                        (255, 0, 0), 2)

            pose_r = np.degrees(detection.camera_rotation)  # Get the pose_R matrix

            pose_r_text = [
                f"Roll: {pose_r[0]}",
                f"Pitch: {pose_r[1]}",
                f"Yaw: {pose_r[2]}",
            ]
            for i, text in enumerate(pose_r_text):
                cv2.putText(frame, text, tuple(center + np.array([10, 80 + i * 20])), cv2.FONT_HERSHEY_SIMPLEX, 0.5,
                            (255, 0, 0), 2)

        return frame